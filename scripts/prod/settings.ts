const EMAIL = /^[a-z0-9.+_-]+@[a-z0-9.-]+$/;
const CLIENT_ID = /^[A-Za-z0-9._-]{1,128}$/;

function q(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

/**
 * Idempotent SQL for the people above. Re-running it converges: rows are inserted when missing and an existing
 * login is pointed at the configured role and row again.
 */
export function peopleSql(people: readonly Person[] = PEOPLE): string {
  const lines = ["-- OnboardFlow production logins (generated by scripts/prod/settings.ts)."];
  for (const p of people) {
    if (!EMAIL.test(p.email)) throw new Error(`not an email: ${p.email}`);
    if ((p.role === "employee") !== (p.employeeId !== undefined)) throw new Error(`${p.email}: employees need employeeId, others staffId`);
    if (p.staffId === "P01") {
      lines.push(`INSERT INTO staff (id, email, display_name, kind, department, org_unit) VALUES ('P01', ${q(p.email)}, 'Nitish (owner)', 'admin', NULL, NULL) ON CONFLICT(id) DO UPDATE SET email = excluded.email, kind = 'admin';`);
    }
    lines.push(
      `INSERT INTO app_users (email, role, employee_id, staff_id, active) VALUES (${q(p.email)}, ${q(p.role)}, ${p.employeeId ? q(p.employeeId) : "NULL"}, ${p.staffId ? q(p.staffId) : "NULL"}, 1)` +
        " ON CONFLICT(email) DO UPDATE SET role = excluded.role, employee_id = excluded.employee_id, staff_id = excluded.staff_id, active = 1;",
    );
  }
  return `${lines.join("\n")}\n`;
}

/** The identity verifyAccessJwt gives an Access service token (src/worker/auth/access.ts). */
export function serviceIdentity(clientId: string): string {
  if (!CLIENT_ID.test(clientId)) throw new Error("service token client id has an unexpected format");
  return `service-token:${clientId.toLowerCase()}`;
}

/** Idempotent SQL that makes the verification service token an admin, and retires any earlier token's identity. */
export function serviceIdentitySql(clientId: string): string {
  const id = serviceIdentity(clientId);
  return [
    "-- OnboardFlow production verification principal (generated by scripts/prod/settings.ts).",
    `INSERT INTO staff (id, email, display_name, kind, department, org_unit) VALUES (${q(SERVICE_STAFF_ID)}, ${q(id)}, 'Production verification (service token)', 'admin', NULL, NULL) ON CONFLICT(id) DO UPDATE SET email = excluded.email;`,
    `UPDATE app_users SET active = 0 WHERE email LIKE 'service-token:%' AND email <> ${q(id)};`,
    `INSERT INTO app_users (email, role, employee_id, staff_id, active) VALUES (${q(id)}, 'admin', NULL, ${q(SERVICE_STAFF_ID)}, 1) ON CONFLICT(email) DO UPDATE SET role = 'admin', staff_id = excluded.staff_id, active = 1;`,
    "",
  ].join("\n");
}
